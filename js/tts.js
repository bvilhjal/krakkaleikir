/* Neural-TTS audio playback for Krakkaleikir.
   Plays pre-generated mp3s from audio/<lang>/<key>.mp3 (see js/audio-manifest.js,
   generated by tools/make_audio.py). Falls back to Web Speech (KL.speak) if an
   audio file is missing or Audio is unavailable. Load after i18n.js/sound.js.

   Only one sequence plays at a time: each say() invalidates any sequence still
   in flight (generation token), and each file is finished exactly once (a
   play() rejection and a later error event must not both advance the queue).
   say(parts, onDone) calls onDone once the whole sequence finished (or right
   away when muted/empty), so callers can wait for speech before advancing. */
(function () {
  'use strict';

  // site base path, works both at /krakkaleikir/ and /krakkaleikir/games/x.html
  function base() {
    var p = window.location.pathname;
    var gi = p.indexOf('/games/');
    if (gi >= 0) return p.slice(0, gi + 1);
    return p.replace(/[^/]*$/, '');
  }

  var current = null;
  var token = 0;

  function urlFor(key) {
    // cache-buster: count of manifest keys changes whenever audio is regenerated,
    // so a stale cached 404/old file is never reused
    var m = window.KL_AUDIO && window.KL_AUDIO[window.KL_I18N.lang()];
    var v = m ? Object.keys(m).length : 0;
    return base() + 'audio/' + window.KL_I18N.lang() + '/' + encodeURIComponent(key) + '.mp3?v=' + v;
  }

  function textFor(key) {
    var m = window.KL_AUDIO && window.KL_AUDIO[window.KL_I18N.lang()];
    if (m && m[key]) return m[key];
    // manifest missing/stale: speak the raw syllable/word, not the "syl.xxx" key
    return key.replace(/^[a-z]+\./, '');
  }

  function stop() {
    token++;
    if (current) {
      try { current.pause(); current.onended = null; current.onerror = null; } catch (e) { /* ignore */ }
      current = null;
    }
  }

  /* parts: array of audio keys, played in order. onDone: optional callback. */
  function say(parts, onDone) {
    if (window.KL_SOUND && !window.KL_SOUND.on()) { if (onDone) setTimeout(onDone, 0); return; }
    if (!parts || !parts.length) { if (onDone) setTimeout(onDone, 0); return; }
    stop();
    var gen = token;
    var i = 0;
    function fallback(key) {
      try { window.KL.speak(textFor(key)); } catch (e) { /* ignore */ }
    }
    function next() {
      if (gen !== token) return; // a newer say()/stop() superseded this sequence
      if (i >= parts.length) { current = null; if (onDone) onDone(); return; }
      var key = parts[i++];
      if (typeof Audio === 'undefined') { fallback(key); next(); return; }
      var a = new Audio();
      a.preload = 'auto';
      var done = false;
      function finish(useFallback) {
        if (done || gen !== token) return;
        done = true;
        if (useFallback) fallback(key);
        next();
      }
      a.onended = function () { finish(false); };
      a.onerror = function () { finish(true); };
      current = a;
      a.src = urlFor(key);
      var p;
      try { p = a.play(); } catch (e) { finish(true); return; }
      if (p && p.catch) p.catch(function () { finish(true); });
    }
    next();
  }

  window.KL_TTS = { say: say, stop: stop };
})();
