/* Neural-TTS audio playback for Krakkaleikir.
   Plays pre-generated mp3s from audio/<lang>/<key>.mp3 (see js/audio-manifest.js,
   generated by tools/make_audio.py). Falls back to Web Speech (KL.speak) if an
   audio file is missing or Audio is unavailable. Load after i18n.js/sound.js.

   All speech goes through one shared <audio> element: iOS lets an element that
   has played once inside a tap play again later without one, so after the first
   tap anywhere in the app every later prompt can start on its own.

   Only one sequence plays at a time: each say() invalidates any sequence still
   in flight (generation token), and each file is finished exactly once (a
   play() rejection and a later error event must not both advance the queue).
   say(parts, onDone) calls onDone once the whole sequence finished (or right
   away when muted/empty/refused), so callers can wait for speech before advancing.
   When the browser refuses to start audio before a tap, blocked() turns true and
   KL (common.js) says the current prompt again inside the next tap. */
(function () {
  'use strict';

  // site base path, works at /krakkaleikir/, /krakkaleikir/index.html and /krakkaleikir/games/x.html
  function base() {
    var p = window.location.pathname;
    var gi = p.indexOf('/games/');
    if (gi >= 0) return p.slice(0, gi + 1);
    return p.replace(/[^/]*$/, '');
  }

  var el = null;
  var token = 0;
  var busy = false;
  var refused = false;
  var primed = false;

  function audio() {
    if (!el && typeof Audio !== 'undefined') {
      el = new Audio();
      el.preload = 'auto';
    }
    return el;
  }

  function urlFor(key) {
    return base() + 'audio/' + window.KL_I18N.lang() + '/' + encodeURIComponent(key) + '.mp3';
  }

  function textFor(key) {
    var m = window.KL_AUDIO && window.KL_AUDIO[window.KL_I18N.lang()];
    if (m && m[key]) return m[key];
    // manifest missing/stale: speak the raw syllable/word, not the "syl.xxx" key
    return key.replace(/^[a-z]+\./, '');
  }

  // 0.05 s of silence (8 kHz, 8-bit mono WAV) used to unlock the element in a tap
  var silentUrl = null;
  function silence() {
    if (silentUrl) return silentUrl;
    var n = 400, b = new Uint8Array(44 + n), dv = new DataView(b.buffer), i;
    function str(o, s) { for (var k = 0; k < s.length; k++) b[o + k] = s.charCodeAt(k); }
    str(0, 'RIFF'); dv.setUint32(4, 36 + n, true); str(8, 'WAVE'); str(12, 'fmt ');
    dv.setUint32(16, 16, true); dv.setUint16(20, 1, true); dv.setUint16(22, 1, true);
    dv.setUint32(24, 8000, true); dv.setUint32(28, 8000, true); dv.setUint16(32, 1, true); dv.setUint16(34, 8, true);
    str(36, 'data'); dv.setUint32(40, n, true);
    for (i = 0; i < n; i++) b[44 + i] = 128;
    var s = '';
    for (i = 0; i < b.length; i++) s += String.fromCharCode(b[i]);
    silentUrl = 'data:audio/wav;base64,' + window.btoa(s);
    return silentUrl;
  }

  function stop() {
    token++;
    busy = false;
    if (el) {
      try { el.onended = null; el.onerror = null; el.pause(); } catch (e) { /* ignore */ }
    }
  }

  /* Call inside a tap: plays silence once so later say() calls may start without a tap. */
  function prime() {
    if (primed || busy) return;
    var a = audio();
    if (!a) return;
    try {
      a.onended = null; a.onerror = null;
      a.src = silence();
      var p = a.play();
      if (p && p.then) p.then(function () { primed = true; }, function () { /* not a gesture: retry on the next tap */ });
    } catch (e) { /* ignore */ }
  }

  /* parts: array of audio keys, played in order. onDone: optional callback. */
  function say(parts, onDone) {
    if (window.KL_SOUND && !window.KL_SOUND.on()) { if (onDone) setTimeout(onDone, 0); return; }
    if (!parts || !parts.length) { if (onDone) setTimeout(onDone, 0); return; }
    stop();
    var gen = token;
    var i = 0;
    busy = true;
    refused = false;
    function fallback(key) {
      try { window.KL.speak(textFor(key)); } catch (e) { /* ignore */ }
    }
    function next() {
      if (gen !== token) return; // a newer say()/stop() superseded this sequence
      if (i >= parts.length) { busy = false; if (onDone) onDone(); return; }
      var key = parts[i++];
      var a = audio();
      if (!a) { fallback(key); next(); return; }
      var done = false;
      function finish(err) {
        if (done || gen !== token) return;
        done = true;
        if (err && err.name === 'NotAllowedError') {
          // autoplay refused (no tap yet): Web Speech would be refused too, so
          // stop here and let the next tap say it again
          refused = true;
          busy = false;
          if (onDone) onDone();
          return;
        }
        if (err) fallback(key);
        next();
      }
      a.onended = function () { finish(null); };
      a.onerror = function () { finish({ name: 'MediaError' }); };
      a.src = urlFor(key);
      var p;
      try { p = a.play(); } catch (e) { finish(e); return; }
      if (p && p.then) p.then(function () { primed = true; }, function (e) { finish(e || { name: 'Error' }); });
    }
    next();
  }

  window.KL_TTS = {
    say: say,
    stop: stop,
    prime: prime,
    blocked: function () { return refused; }
  };
})();
